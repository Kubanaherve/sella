import { inflateSync } from "node:zlib";
import { describe, expect, it } from "vitest";
import { buildDebtReportPdf } from "@/lib/invoicePdf";
import { debtReportFigures, debtReportTableRows } from "@/lib/debtReport";
import { buildListReportPdf } from "@/lib/listReportPdf";

function pdfText(bytes: Uint8Array): string {
  const raw = Buffer.from(bytes).toString("latin1");
  const parts: string[] = [];
  const streams = raw.matchAll(/stream\r?\n([\s\S]*?)\r?\nendstream/g);
  for (const match of streams) {
    try {
      parts.push(inflateSync(Buffer.from(match[1], "latin1")).toString("latin1"));
    } catch {
      parts.push(match[1]);
    }
  }
  return parts.join("\n") || raw;
}

describe("debt report figures", () => {
  it("sums multiple partial payments and keeps unpaid and paid debts", () => {
    expect(
      debtReportFigures({
        name: "A",
        originalAmount: 10000,
        paymentAmounts: [],
      })
    ).toEqual({ total: 10000, paid: 0, remaining: 10000 });
    expect(
      debtReportFigures({
        name: "B",
        originalAmount: 10000,
        paymentAmounts: [2500],
      })
    ).toEqual({ total: 10000, paid: 2500, remaining: 7500 });
    expect(
      debtReportFigures({
        name: "C",
        originalAmount: 8000,
        paymentAmounts: [3000, 2000],
      })
    ).toEqual({ total: 8000, paid: 5000, remaining: 3000 });
    expect(
      debtReportFigures({
        name: "D",
        originalAmount: 4000,
        paymentAmounts: [1500, 2500],
      })
    ).toEqual({ total: 4000, paid: 4000, remaining: 0 });
  });

  it("numbers every debt once, in order, including items", () => {
    const rows = debtReportTableRows([
      {
        name: "Aline",
        createdAt: "2026-11-01T10:00:00.000Z",
        originalAmount: 5000,
        paymentAmounts: [],
        lines: [{ name: "Ring", quantity: 2, unitPrice: 2500 }],
      },
      {
        name: "Claude",
        createdAt: "2026-11-02T10:00:00.000Z",
        originalAmount: 9000,
        paymentAmounts: [1000, 500],
        lines: [
          { name: "Chain", quantity: 1, unitPrice: 4000 },
          { name: "Beads", quantity: 3, unitPrice: 1000 },
        ],
      },
    ]);
    expect(rows[0][0]).toBe("1");
    expect(rows[1][0]).toBe("2");
    expect(rows[0][2]).toBe("Ring × 2");
    expect(rows[1][2]).toBe("Chain × 1\nBeads × 3");
    expect(rows[1][5]).toBe("1,500");
    expect(rows[1][6]).toBe("7,500");
  });
});

describe("compact list PDFs", () => {
  it("prints the debt title once, numbers rows across pages, and omits email", async () => {
    const rows = Array.from({ length: 80 }, (_, index) => ({
      name: index === 3 ? "Uwamahoro Ingabire y'umuryango munini cyane" : `Client ${index + 1}`,
      createdAt: "2026-11-19T08:00:00.000Z",
      originalAmount: 5000 + index,
      paymentAmounts: index % 5 === 0 ? [1000, 500] : index % 2 === 0 ? [200] : [],
      lines: [
        {
          name: index === 7 ? "Gold plated ceremonial necklace with a very long workshop description" : "Ring",
          quantity: 1,
          unitPrice: 5000,
        },
      ],
    }));
    const doc = await buildDebtReportPdf({
      shopName: "Demo Jewel Kigali",
      shopPayPhone: "0788111222",
      shopEmail: "owner@example.com",
      rows: rows.map((row) => ({
        ...row,
        paidAmount: 0,
        remainingAmount: row.originalAmount,
        lines: row.lines,
      })),
      grandTotal: 0,
    });
    expect(doc.getNumberOfPages()).toBeGreaterThan(1);
    const text = pdfText(new Uint8Array(doc.output("arraybuffer")));
    expect(text.split("All Debts").length - 1).toBe(1);
    expect(text).toContain("Generated by Sella");
    expect(text).toContain("Demo Jewel Kigali");
    expect(text).toContain("0788111222");
    expect(text).not.toContain("owner@example.com");
    expect(text).not.toContain("www.sella.app");
    expect(text).toContain("Client Name");
    expect(text).toContain("80");
    expect(text).not.toContain("support@sella.app");
    const raw = Buffer.from(doc.output("arraybuffer")).toString("latin1");
    expect(raw).toContain("/Subtype /Image");
  });

  it("uses each shop's own name and payment number", async () => {
    const first = await buildListReportPdf({
      title: "All Clients",
      shopName: "Shop A",
      paymentNumber: "0788000001",
      columns: [
        { header: "No.", width: 14, align: "right" },
        { header: "Client Name", width: 0 },
        { header: "Phone", width: 36 },
      ],
      rows: [["1", "Aline", "0788123456"]],
    });
    const second = await buildListReportPdf({
      title: "Inventory",
      shopName: "Shop B",
      paymentNumber: "0788000002",
      columns: [
        { header: "No.", width: 14, align: "right" },
        { header: "Product", width: 0 },
        { header: "Qty", width: 20, align: "right" },
      ],
      rows: [["1", "Ring", "4"]],
    });
    const a = pdfText(new Uint8Array(first.output("arraybuffer")));
    const b = pdfText(new Uint8Array(second.output("arraybuffer")));
    expect(a).toContain("Shop A");
    expect(a).toContain("0788000001");
    expect(a).not.toContain("Shop B");
    expect(b).toContain("Shop B");
    expect(b).toContain("0788000002");
    expect(b).toContain("Generated by Sella");
  });
});
