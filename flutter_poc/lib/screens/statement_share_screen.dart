import 'dart:io';
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:share_plus/share_plus.dart';

import '../data/mock_data.dart';
import '../theme/sella_theme.dart';

class StatementShareScreen extends StatefulWidget {
  const StatementShareScreen({super.key});

  @override
  State<StatementShareScreen> createState() => _StatementShareScreenState();
}

class _StatementShareScreenState extends State<StatementShareScreen> {
  String _status = 'idle';
  String? _error;

  String get _message {
    final c = mockCustomer;
    final items = c.lines.map((l) => '${l.name}: ${l.quantity}').join(' , ');
    return [
      'Muraho mukiliya mwiza twifuzaga kubibutsa ko mufite mwafashe ibi bintu bikurikira',
      '($items )',
      'nimubone umwanya murebe PDF twabahaye muze kuyigenderaho mwishyura.',
      'Turabashimiye cyane!',
      '',
      'Murakoze kugana ${MockShop.name}',
      'Ishura kuri: ${MockShop.payPhone}',
    ].join('\n');
  }

  Future<Uint8List> _buildPdfBytes() async {
    final c = mockCustomer;
    final doc = pw.Document();
    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.all(16),
                color: PdfColor.fromInt(0xFF0B4FD9),
                child: pw.Text(
                  'INVOICE · Sella',
                  style: pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 22,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
              ),
              pw.SizedBox(height: 16),
              pw.Text('Bill To: ${c.name}'),
              pw.Text(c.phone),
              pw.Text('From: ${MockShop.name}'),
              pw.SizedBox(height: 16),
              pw.TableHelper.fromTextArray(
                headers: ['Item', 'Qty', 'Total'],
                data: c.lines
                    .map(
                      (l) => [
                        l.name,
                        '${l.quantity}',
                        formatRwf(l.lineTotal),
                      ],
                    )
                    .toList(),
              ),
              pw.SizedBox(height: 16),
              pw.Text('Yishyuwe: ${formatRwf(c.paid)}'),
              pw.Text(
                'Asigaye: ${formatRwf(c.remaining)}',
                style: pw.TextStyle(
                  color: PdfColor.fromInt(0xFFB91C1C),
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
              pw.SizedBox(height: 12),
              pw.Text('Ishura kuri: ${MockShop.payPhone}'),
              pw.Spacer(),
              pw.Center(
                child: pw.Text(
                  'Generated by Sella · mock PoC',
                  style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey),
                ),
              ),
            ],
          );
        },
      ),
    );
    return doc.save();
  }

  Future<void> _share() async {
    setState(() {
      _status = 'preparing';
      _error = null;
    });
    try {
      final bytes = await _buildPdfBytes();
      setState(() => _status = 'opening');
      final dir = await getTemporaryDirectory();
      final file = File('${dir.path}/Sella_Ideni_${mockCustomer.name}.pdf');
      await file.writeAsBytes(bytes, flush: true);
      await SharePlus.instance.share(
        ShareParams(
          text: _message,
          files: [XFile(file.path, mimeType: 'application/pdf')],
          title: 'Kohereza kwibutsa kuri WhatsApp',
        ),
      );
      if (mounted) setState(() => _status = 'done');
    } catch (e) {
      if (mounted) {
        setState(() {
          _status = 'error';
          _error = e.toString();
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final c = mockCustomer;
    final busy = _status == 'preparing' || _status == 'opening';

    return Scaffold(
      backgroundColor: SellaColors.sand,
      appBar: AppBar(
        title: const Text('Statement & Share'),
        leading: IconButton(
          icon: const Icon(Icons.close_rounded),
          onPressed: () => Navigator.of(context).pop(),
        ),
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(20, 16, 20, 32),
        children: [
          AnimatedContainer(
            duration: const Duration(milliseconds: 280),
            curve: Curves.easeOutCubic,
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: Colors.white,
              borderRadius: BorderRadius.circular(20),
              border: Border.all(color: const Color(0xFFE2E8F0)),
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(14),
                  decoration: BoxDecoration(
                    color: SellaColors.blueDeep,
                    borderRadius: BorderRadius.circular(14),
                  ),
                  child: Row(
                    children: [
                      Image.asset('assets/brand/sella-icon.png', width: 28, height: 28),
                      const SizedBox(width: 10),
                      Text(
                        'INVOICE PREVIEW',
                        style: GoogleFonts.plusJakartaSans(
                          color: Colors.white,
                          fontWeight: FontWeight.w800,
                          fontSize: 14,
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 14),
                Text(
                  c.name,
                  style: GoogleFonts.plusJakartaSans(
                    fontWeight: FontWeight.w800,
                    fontSize: 18,
                  ),
                ),
                Text(
                  c.phone,
                  style: GoogleFonts.plusJakartaSans(
                    color: SellaColors.muted,
                    fontSize: 13,
                  ),
                ),
                const SizedBox(height: 12),
                ...c.lines.map(
                  (l) => Padding(
                    padding: const EdgeInsets.only(bottom: 8),
                    child: Row(
                      children: [
                        Expanded(
                          child: Text(
                            '${l.name} × ${l.quantity}',
                            style: GoogleFonts.plusJakartaSans(fontSize: 14),
                          ),
                        ),
                        Text(
                          formatRwf(l.lineTotal),
                          style: GoogleFonts.plusJakartaSans(
                            fontWeight: FontWeight.w700,
                            fontSize: 14,
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
                const Divider(height: 24),
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Text(
                      'Asigaye',
                      style: GoogleFonts.plusJakartaSans(
                        fontWeight: FontWeight.w700,
                        color: SellaColors.danger,
                      ),
                    ),
                    Text(
                      formatRwf(c.remaining),
                      style: GoogleFonts.plusJakartaSans(
                        fontWeight: FontWeight.w800,
                        color: SellaColors.danger,
                        fontSize: 18,
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 8),
                Text(
                  'Ishura kuri: ${MockShop.payPhone}',
                  style: GoogleFonts.plusJakartaSans(
                    fontSize: 13,
                    color: SellaColors.muted,
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 16),
          Container(
            padding: const EdgeInsets.all(14),
            decoration: BoxDecoration(
              color: Colors.white,
              borderRadius: BorderRadius.circular(16),
              border: Border.all(color: const Color(0xFFE2E8F0)),
            ),
            child: Text(
              _message,
              style: GoogleFonts.plusJakartaSans(
                fontSize: 13,
                height: 1.45,
                color: SellaColors.ink,
              ),
            ),
          ),
          const SizedBox(height: 20),
          if (busy)
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: const Color(0xFFF0FDF4),
                borderRadius: BorderRadius.circular(14),
              ),
              child: Row(
                children: [
                  const SizedBox(
                    width: 18,
                    height: 18,
                    child: CircularProgressIndicator(strokeWidth: 2),
                  ),
                  const SizedBox(width: 12),
                  Text(
                    _status == 'preparing'
                        ? 'Preparing customer statement…'
                        : 'Opening share sheet…',
                    style: GoogleFonts.plusJakartaSans(
                      fontWeight: FontWeight.w700,
                      fontSize: 14,
                    ),
                  ),
                ],
              ),
            ),
          if (_error != null) ...[
            const SizedBox(height: 12),
            Text(
              _error!,
              style: GoogleFonts.plusJakartaSans(
                color: SellaColors.danger,
                fontSize: 12,
              ),
            ),
          ],
          const SizedBox(height: 16),
          SizedBox(
            width: double.infinity,
            child: ElevatedButton.icon(
              onPressed: busy ? null : _share,
              style: ElevatedButton.styleFrom(
                backgroundColor: SellaColors.whatsapp,
                foregroundColor: Colors.white,
                disabledBackgroundColor:
                    SellaColors.whatsapp.withValues(alpha: 0.5),
                minimumSize: const Size.fromHeight(58),
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(18),
                ),
              ),
              icon: const Icon(Icons.ios_share_rounded),
              label: Text(
                busy ? 'Please wait…' : 'Share PDF and Message',
                style: GoogleFonts.plusJakartaSans(
                  fontWeight: FontWeight.w800,
                  fontSize: 16,
                ),
              ),
            ),
          ),
          const SizedBox(height: 10),
          Center(
            child: Text(
              'Mock PDF · does not use production data',
              style: GoogleFonts.plusJakartaSans(
                fontSize: 11,
                color: SellaColors.muted,
              ),
            ),
          ),
        ],
      ),
    );
  }
}
